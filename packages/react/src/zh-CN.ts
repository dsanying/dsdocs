export const zhCNTranslation: NonNullable<MDXEditorProps['translation']> = (
  key,
  fallback,
  interpolations = {}
) => {
  let value = messages[key] ?? fallback;
  for (const [name, replacement] of Object.entries(interpolations))
    value = value.replaceAll(`{{${name}}}`, String(replacement));
  return value;
};
